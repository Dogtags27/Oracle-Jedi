export type FindingsT = TranslatorFor<typeof FINDINGS>;
export type FindingsKey = keyof typeof FINDINGS.en;

export const findingsT = (locale: Locale): FindingsT => translator(FINDINGS, locale);

export const verdictTitle = (v: Verdict, locale: Locale) => findingsT(locale)(`verdict.${v}`);
export const verdictTip = (v: Verdict, locale: Locale) => findingsT(locale)(`verdict.${v}.tip`);
export const itemLabel = (code: RequestItem, locale: Locale) => findingsT(locale)(`item.${code}`);
export const credentialLabel = (code: CredentialAsk, locale: Locale) => findingsT(locale)(`cred.${code}`);
export const pressureLabel = (code: PressureSignal, locale: Locale) => findingsT(locale)(`pressure.${code}`);
export const kindLabel = (kind: FindingKind, locale: Locale, count = 1) => findingsT(locale)(`kind.${kind}`, { count });

export function describeKinds(counts: Partial<Record<FindingKind, number>>, order: FindingKind[], locale: Locale): string {
  const parts = order.filter((k) => counts[k]).map((k) => `${counts[k]} ${kindLabel(k, locale, counts[k]!)}`);
  if (!parts.length) return "";
  if (locale === "en") return parts.length === 1 ? parts[0]! : `${parts.slice(0, -1).join(", ")} and ${parts.at(-1)}`;
  return formatters(locale).list(parts);
}

export function linkReasons(check: Pick<LinkCheck, "reasons" | "facts">, locale: Locale): string[] {
  if (!check.facts?.length) return check.reasons;
  const t = findingsT(locale);
  return check.facts.map((f) => t(`risk.${f.key}`, f.vars));
}

export function attachmentReason(a: Pick<AttachmentCheck, "reason" | "code" | "disguised" | "ext">, locale: Locale): string {
  if (!a.code) return a.reason;
  const t = findingsT(locale);
  const lead = a.disguised && a.code !== "macros" && a.code !== "archive" ? t("attach.disguised", { ext: a.ext }) : "";
  return `${lead}${t(`attach.${a.code}`)}`;
}

export function signalText(fact: CheckFact, locale: Locale): string {
  return findingsT(locale)(`signal.${fact.code}`, fact.vars);
}

export function checkSignals(r: Pick<CheckResponse, "signals" | "facts">, locale: Locale): string[] {
  if (!r.facts) return r.signals;
  return [...new Set(r.facts.map((f) => signalText(f, locale)))];
}

export function isGoodSignal(r: Pick<CheckResponse, "verdict">, fact: CheckFact | string): boolean {
  if (r.verdict !== "verified") return false;
  if (typeof fact === "string") return /match/i.test(fact) && !/doesn't|isn't|not /i.test(fact);
  return fact.code === "phone_match";
}

export interface ExplainInput {
  verdict: Verdict;
  claimedOrg: string;
  sender?: string;
  officialDomain?: string;
  officialPhone?: string;
}

export function explainCheck(x: ExplainInput, locale: Locale): string {
  const t = findingsT(locale);
  const who = x.sender || t("explain.thisSender");
  const vars: Vars = { who, org: x.claimedOrg, domain: x.officialDomain ?? "", phone: x.officialPhone ?? "" };
  const call = x.officialPhone ? t("explain.call", vars) : "";
  if (x.verdict === "verified") return `${t("explain.verified", vars)}${call}`;
  if (x.verdict === "mismatch") return `${t("explain.mismatch", vars)}${call}`;
  return t("explain.unknown", vars);
}

export function checkExplanation(r: CheckResponse, locale: Locale): string {
  if (!r.facts) return r.explanation;
  return explainCheck({ verdict: r.verdict, claimedOrg: r.claimedOrg, sender: r.sender, officialDomain: r.officialDomain, officialPhone: r.officialPhone }, locale);
}

const QUOTES: Record<Locale, [string, string]> = { en: ["“", "”"], es: ["«", "»"], fr: ["« ", " »"], de: ["„", "“"], pt: ["“", "”"] };

export function quoteLabel(label: string, locale: Locale): string {
  const l = label.replace(/\s+/g, " ").trim();
  if (!l) return findingsT(locale)("click.thisButton");
  const [open, close] = QUOTES[locale];
  return `${open}${l.length > 32 ? `${l.slice(0, 31)}…` : l}${close}`;
}

export type ClickMsgKey =
  | "dismiss"
  | "overlay"
  | "extra"
  | "plain"
  | "doc"
  | "dismissStatic"
  | "overlayStatic"
  | "mismatch"
  | "userinfo"
  | "punycode"
  | "extraStatic"
  | "decoy"
  | "form"
  | "formWould"
  | "frame"
  | "notification";

export interface ClickMsg {
  key: ClickMsgKey;
  vars?: Record<string, string>;
}

export function clickText(msg: ClickMsg, locale: Locale): string {
  const t = findingsT(locale);
  const vars: Record<string, string> = { ...msg.vars };
  if ("label" in vars) vars.label = quoteLabel(vars.label ?? "", locale);
  if ("from" in vars && !vars.from) vars.from = t("click.thisSite");
  return t(`click.${msg.key}`, vars);
}

export function clickReason(v: { reason: string; msg?: ClickMsg }, locale: Locale): string {
  return v.msg ? clickText(v.msg, locale) : v.reason;
}
